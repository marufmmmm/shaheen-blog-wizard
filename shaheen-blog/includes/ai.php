                    $t = is_string($t) ? sanitize_text_field($t) : '';
                    if (mb_strlen($t) >= 8) {
                        $o[$k][] = $t;
                    }
                }
            }
            return $o;
        }
        if ($feature === 'rewrite_post') {
            $j = json_decode($text, true);
            if (!is_array($j) || empty($j['article'])) {
                return new WP_Error('sb_json', 'AI-এর উত্তর পড়া যায়নি। আবার চেষ্টা করুন।');
            }
